export function getCinemasForCity(cityName) {
  if (!cityName) return cityCinemas["Mumbai"];
  const cleanName = cityName.trim();
  const normalizedKey = cleanName.toLowerCase();

  // 1. Direct match in cityAliases
  const mappedKey = cityAliases[normalizedKey];
  if (mappedKey && cityCinemas[mappedKey]) {
    return cityCinemas[mappedKey];
  }

  // 2. Direct key match in cityCinemas (case-insensitive)
  const exactKey = Object.keys(cityCinemas).find(
    (key) => key.toLowerCase() === normalizedKey
  );
  if (exactKey) {
    return cityCinemas[exactKey];
  }

  // 3. Substring match
  const partialKey = Object.keys(cityCinemas).find(
    (key) => normalizedKey.includes(key.toLowerCase()) || key.toLowerCase().includes(normalizedKey)
  );
  if (partialKey) {
    return cityCinemas[partialKey];
  }

  // 4. Generate 7 realistic cinemas for the city dynamically
  return generateDynamicCinemas(cleanName);
}

